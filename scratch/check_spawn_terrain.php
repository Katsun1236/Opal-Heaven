<?php
require 'server/pmmp_src/vendor/autoload.php';

use pocketmine\world\format\io\leveldb\LevelDB;

$logger = new class extends \SimpleLogger {
    public function log($level, $message) {}
};

try {
    $db = new LevelDB('server/worlds/world', $logger);
} catch (\Throwable $e) {
    echo "Could not open world directly: " . $e->getMessage() . "\nTrying world_backup...\n";
    $db = new LevelDB('server/worlds/world_backup', $logger);
}
$worldData = $db->getWorldData();
echo "Spawn: " . $worldData->getSpawn() . "\n";
echo "Generator: " . $worldData->getGenerator() . "\n";

$chunk = $db->loadChunk(16, 16);
if($chunk !== null) {
    echo "Chunk (16, 16) found in DB!\n";
    $subChunkCount = 0;
    foreach($chunk->getSubChunks() as $y => $subChunk) {
        if(!$subChunk->isEmpty()) {
            $subChunkCount++;
        }
    }
    echo "Non-empty subchunks: $subChunkCount\n";
    $highestY = $chunk->getHighestBlockAt(0, 0);
    echo "Highest block at (256, 256): Y=$highestY\n";
    for($y = 65; $y <= 90; $y++) {
        $state = $chunk->getBlockStateId(0, $y, 0);
        if($state !== 0) {
            echo "Y=$y -> StateId: $state\n";
        }
    }
} else {
    echo "Chunk (16, 16) NOT in DB (will be generated by opal generator)\n";
}
